// Bundles the CLI (and the `yaml` dependency) into one file that the composite action runs: action/index.mjs
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
for (const [entry, outfile] of [['src/cli.ts', 'action/index.mjs'], ['src/comment-cli.ts', 'action/comment.mjs']])
await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  banner: { js: `// dependabot-gaps ${pkg.version} - generated by scripts/bundle.mjs, do not edit\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);` },
  logLevel: 'info',
});
